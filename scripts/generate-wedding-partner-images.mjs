import crypto from 'node:crypto';
import { mkdir, readdir, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const sourceRoot = process.argv[2] || process.env.WEDDING_PARTNER_IMAGE_SOURCE;

if (!sourceRoot) {
  console.error('Usage: node scripts/generate-wedding-partner-images.mjs <download-folder>');
  process.exit(1);
}

const repoRoot = process.cwd();
const outputRoot = path.join(repoRoot, 'apps/web/public/images/wedding-partners');
const manifestPath = path.join(repoRoot, 'apps/web/src/lib/wedding-partner-images.ts');

const CATEGORY_RULES = [
  { test: '웨딩홀', category: '웨딩홀', slug: 'wedding-hall' },
  { test: '피부과', category: '피부과', slug: 'dermatology' },
  { test: 'DVD', category: 'DVD', slug: 'dvd' },
  { test: '스튜디오', category: '스튜디오', slug: 'studio' },
  { test: '드레스', category: '드레스', slug: 'dress' },
  { test: '헤메샵', category: '메이크업', slug: 'hair-makeup' },
  { test: '본식스냅', category: '스냅', slug: 'ceremony-snap' },
];

const IMAGE_EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp']);

function normalizeText(value) {
  return value.normalize('NFC');
}

function slugHash(value) {
  return crypto.createHash('sha1').update(normalizeText(value)).digest('hex').slice(0, 8);
}

function inferCategory(folderName) {
  const normalized = normalizeText(folderName);
  return CATEGORY_RULES.find((rule) => normalized.includes(rule.test)) || {
    category: normalized.replace(/^\d+/, ''),
    slug: `misc-${slugHash(normalized)}`,
  };
}

function normalizeManifestKey(value) {
  return normalizeText(value)
    .toLowerCase()
    .replace(/[()[\]{}（）]/g, '')
    .replace(/주식회사|유한회사|\(주\)|㈜/g, '')
    .replace(/[\s·ㆍ.,'"`~!@#$%^&*_+=/\\|:;?<>-]/g, '');
}

function imageSortKey(fileName) {
  const normalized = normalizeText(fileName);
  if (normalized.includes('업체대표사진')) return -1000;
  const numbered = normalized.match(/(?:사진|image|img|kakaotalk|_)(\d+)/i);
  if (numbered) return Number(numbered[1]);
  const leading = normalized.match(/^(\d+)/);
  if (leading) return Number(leading[1]);
  return 10000;
}

async function listDirs(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  return entries
    .filter((entry) => entry.isDirectory())
    .map((entry) => path.join(dir, entry.name))
    .sort((a, b) => normalizeText(path.basename(a)).localeCompare(normalizeText(path.basename(b)), 'ko'));
}

async function listImages(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = entries
    .filter((entry) => entry.isFile() && IMAGE_EXTENSIONS.has(path.extname(entry.name).toLowerCase()))
    .map((entry) => path.join(dir, entry.name));

  return files.sort((a, b) => {
    const aName = path.basename(a);
    const bName = path.basename(b);
    const orderDiff = imageSortKey(aName) - imageSortKey(bName);
    if (orderDiff !== 0) return orderDiff;
    return normalizeText(aName).localeCompare(normalizeText(bName), 'ko', { numeric: true });
  });
}

async function convertImage(inputPath, outputPath) {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await sharp(inputPath, { failOn: 'none' })
    .rotate()
    .resize({ width: 1400, height: 1400, fit: 'inside', withoutEnlargement: true })
    .webp({ quality: 78, effort: 4 })
    .toFile(outputPath);
}

function toManifestContent(imageSets, sourceSummary) {
  return `// This file is generated by scripts/generate-wedding-partner-images.mjs.
// Source: ${sourceSummary}

export interface WeddingPartnerImageSet {
  category: string;
  images: readonly string[];
}

export const WEDDING_PARTNER_IMAGE_SETS = ${JSON.stringify(imageSets, null, 2)} as const satisfies Record<string, WeddingPartnerImageSet>;

export function normalizeWeddingPartnerName(value?: string | null) {
  return String(value || '')
    .normalize('NFC')
    .toLowerCase()
    .replace(/[()[\\]{}（）]/g, '')
    .replace(/주식회사|유한회사|\\(주\\)|㈜/g, '')
    .replace(/[\\s·ㆍ.,'"\\\`~!@#$%^&*_+=/\\\\|:;?<>-]/g, '');
}

export function getWeddingPartnerImageSet(...names: Array<string | null | undefined>) {
  const imageSets = WEDDING_PARTNER_IMAGE_SETS as Record<string, WeddingPartnerImageSet>;
  const keys = Object.keys(imageSets);

  for (const name of names) {
    const normalized = normalizeWeddingPartnerName(name);
    if (!normalized) continue;
    const exact = imageSets[normalized];
    if (exact) return exact;

    if (normalized.length >= 4) {
      const looseMatches = keys.filter((key) => (
        key.length >= 4 && (key.includes(normalized) || normalized.includes(key))
      ));
      if (looseMatches.length === 1) return imageSets[looseMatches[0]];
    }
  }

  return undefined;
}

export function getWeddingPartnerImages(...names: Array<string | null | undefined>) {
  return getWeddingPartnerImageSet(...names)?.images || [];
}

export function getWeddingPartnerCategory(...names: Array<string | null | undefined>) {
  return getWeddingPartnerImageSet(...names)?.category;
}

export function getWeddingPartnerSectionCategories(imageSet?: WeddingPartnerImageSet) {
  const categories = imageSet?.category ? [imageSet.category] : [];
  if (imageSet?.images.some((image) => image.includes('/hair-makeup/'))) {
    categories.push('헤어', '메이크업');
  }

  return Array.from(new Set(categories.filter(Boolean)));
}

export function mergeWeddingPartnerImages(...groups: Array<ReadonlyArray<string | null | undefined> | undefined>) {
  const seen = new Set<string>();
  const merged: string[] = [];

  for (const group of groups) {
    if (!Array.isArray(group)) continue;
    for (const image of group) {
      if (!image || seen.has(image)) continue;
      seen.add(image);
      merged.push(image);
    }
  }

  return merged;
}
`;
}

async function main() {
  const sourceStat = await stat(sourceRoot).catch(() => null);
  if (!sourceStat?.isDirectory()) {
    console.error(`Source folder does not exist: ${sourceRoot}`);
    process.exit(1);
  }

  await rm(outputRoot, { recursive: true, force: true });
  await mkdir(outputRoot, { recursive: true });

  const imageSets = {};
  let businessCount = 0;
  let imageCount = 0;

  const categoryDirs = await listDirs(sourceRoot);
  for (const categoryDir of categoryDirs) {
    const categoryFolder = path.basename(categoryDir);
    const category = inferCategory(categoryFolder);
    const businessDirs = await listDirs(categoryDir);

    for (const businessDir of businessDirs) {
      const businessName = normalizeText(path.basename(businessDir));
      const images = await listImages(businessDir);
      if (images.length === 0) continue;

      businessCount += 1;
      const businessSlug = `${String(businessCount).padStart(3, '0')}-${slugHash(businessName)}`;
      const publicImages = [];

      for (let i = 0; i < images.length; i += 1) {
        const outputName = `${String(i + 1).padStart(2, '0')}.webp`;
        const outputPath = path.join(outputRoot, category.slug, businessSlug, outputName);
        await convertImage(images[i], outputPath);
        publicImages.push(`/images/wedding-partners/${category.slug}/${businessSlug}/${outputName}`);
        imageCount += 1;

        if (imageCount % 50 === 0) {
          console.log(`Converted ${imageCount} images...`);
        }
      }

      imageSets[normalizeManifestKey(businessName)] = {
        category: category.category,
        images: publicImages,
      };
    }
  }

  await writeFile(manifestPath, toManifestContent(imageSets, normalizeText(path.basename(sourceRoot))), 'utf8');
  console.log(`Done. ${businessCount} partners, ${imageCount} images.`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
